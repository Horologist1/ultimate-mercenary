// Función para obtener un mensaje aleatorio de una categoría
function getRandomMessage(category, rating = 'normal') {
    const messages = getMessagesByCategory(category, rating);
    if (messages.length === 0) return "¡Increíble actuación!";
    
    const randomIndex = Math.floor(Math.random() * messages.length);
    return messages[randomIndex];
}

